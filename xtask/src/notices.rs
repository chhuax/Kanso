/// 生成“Rust 依赖表 + 许可证文本”两节：依赖集合取 `trees` 里各条 `cargo tree` 命令输出的并集。
fn rust_section(
    target: &str,
    trees: &[Vec<String>],
    graph: &str,
) -> Result<String, Box<dyn Error>> {
    let metadata: Value = serde_json::from_str(&output(&[
        "metadata",
        "--format-version",
        "1",
        "--locked",
        "--all-features",
        "--filter-platform",
        target,
    ])?)?;
    let mut product = BTreeSet::new();
    for tree_args in trees {
        let mut args: Vec<&str> = tree_args.iter().map(String::as_str).collect();
        args.extend([
            "--edges",
            "normal",
            "--prefix",
            "none",
            "--format",
            "{p}",
            "--no-dedupe",
        ]);
        let tree = output(&args)?;
        product.extend(tree.lines().filter_map(|line| {
            let mut parts = line.split_whitespace();
            Some((
                parts.next()?.to_owned(),
                parts.next()?.strip_prefix('v')?.to_owned(),
            ))
        }));
    }
    let members = metadata["workspace_members"].as_array().unwrap();
    let mut packages: Vec<_> = metadata["packages"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|package| !members.contains(&package["id"]))
        .filter(|package| {
            product.contains(&(
                package["name"].as_str().unwrap().to_owned(),
                package["version"].as_str().unwrap().to_owned(),
            ))
        })
        .collect();
    packages.sort_by_key(|package| {
        (
            package["name"].as_str().unwrap(),
            package["version"].as_str().unwrap(),
        )
    });
    let mut text = format!(
        "## Rust dependencies\n\n\
         Metadata comes from `cargo metadata`; `cargo tree` selects the normal dependency graph \
         {graph}, excluding workspace crates, dev dependencies \
         and build-only tools. Proc-macro dependencies in that graph are included.\n\n\
         | Name | Version | License (SPDX) | Source repository |\n\
         | --- | --- | --- | --- |\n",
    );
    let mut licenses = LicenseTexts::new();
    let mut missing = Vec::new();
    for package in packages {
        let name = package["name"].as_str().unwrap();
        let version = package["version"].as_str().unwrap();
        let spdx = package["license"].as_str().ok_or("缺少依赖 SPDX 许可")?;
        let manifest = Path::new(package["manifest_path"].as_str().unwrap());
        let identity = format!("{name}@{version}");
        if !collect_license_files(manifest.parent().unwrap(), &identity, &mut licenses)? {
            missing.push(format!("{identity} ({spdx})"));
            for (identifier, license) in
                standard_licenses(spdx).map_err(|e| format!("{identity}: {e}"))?
            {
                licenses.entry((*license).to_owned()).or_default().insert(format!(
                    "{identity} — SPDX standard text `{identifier}` (upstream license file missing)"
                ));
            }
        }
        writeln!(
            text,
            "| {} | {} | {} | {} |",
            package["name"].as_str().unwrap(),
            package["version"].as_str().unwrap(),
            package["license"].as_str().ok_or("缺少依赖 SPDX 许可")?,
            // 个别 crate 没有声明仓库（如 gpui-macros）：退回 homepage，再退回 crates.io 页面。
            package["repository"]
                .as_str()
                .or_else(|| package["homepage"].as_str())
                .map_or_else(|| format!("https://crates.io/crates/{name}"), str::to_owned),
        )?;
    }
    text.push_str(
        "\n## License and notice texts\n\n\
         Files named LICENSE*, LICENCE*, COPYING* and NOTICE* are copied verbatim from each \
         crate's manifest directory. Only exactly identical texts are grouped together.\n\n",
    );
    if !missing.is_empty() {
        text.push_str(
            "### Crates without upstream license files\n\n\
             The following published crates contain no license file in their manifest directory. \
             Standard texts for their declared SPDX licenses are included below, from \
             https://github.com/spdx/license-list-data/tree/main/text. \
             Template placeholders are retained; no copyright holder is inferred.\n\n",
        );
        for package in &missing {
            writeln!(text, "- {package}")?;
            eprintln!("缺少许可证文件：{package}");
        }
        text.push('\n');
    }
    for (index, (license, users)) in licenses.iter().enumerate() {
        writeln!(
            text,
            "### License / notice text {}\n\nUsed by:\n",
            index + 1
        )?;
        for user in users {
            writeln!(text, "- {user}")?;
        }
        let fence = "`".repeat(
            license
                .lines()
                .map(|line| {
                    line.chars()
                        .take_while(|character| *character == '`')
                        .count()
                })
                .max()
                .unwrap_or(0)
                .max(2)
                + 1,
        );
        writeln!(text, "\n{fence}text")?;
        text.push_str(license);
        if !license.ends_with('\n') {
            text.push('\n');
        }
        writeln!(text, "{fence}\n")?;
    }
    Ok(text)
}

/// Windows 发行包（kanso-gpui，x86_64-pc-windows-msvc）的第三方声明，写入单独的文件，不改动 macOS 的声明。
fn write_windows_notices() -> Result<(), Box<dyn Error>> {
    let trees = vec![
        [
            "tree",
            "-p",
            "kanso-gpui",
            "--locked",
            "--target",
            "x86_64-pc-windows-msvc",
        ]
        .map(String::from)
        .to_vec(),
    ];
    let mut text = rust_section(
        "x86_64-pc-windows-msvc",
        &trees,
        "of `kanso-gpui` (x86_64-pc-windows-msvc, including its Windows-only dependencies)",
    )?;
    text.insert_str(
        0,
        "# Third-party notices (Windows)\n\n\
         Generated by `cargo xtask notices`. Do not edit this file by hand. \
         Covers the Windows package built by `cargo xtask win-package`.\n\n",
    );
    text.push_str(
        "\n## Windows GPUI icons\n\nSource: Lucide Icons, revision `149eba0aea48178a5ab1efe2c701de1da94f4be8`.\n\nLocation: `crates/kanso-gpui/assets/icons`.\n\n",
    );
    text.push_str(include_str!("../../crates/kanso-gpui/assets/icons/LICENSE"));
    text.push_str(
        "\n\n## Installer\n\nThe installer is built with NSIS (zlib/libpng license), which is a build \
         tool only; no NSIS source is incorporated into Kanso. The installer stub embedded in the setup \
         program is distributed under NSIS's license (https://nsis.sourceforge.io/NSIS_License).\n",
    );
    fs::write("THIRD_PARTY_NOTICES.windows.md", text)?;
    Ok(())
}

fn collect_license_files(
    directory: &Path,
    identity: &str,
    licenses: &mut LicenseTexts,
) -> Result<bool, Box<dyn Error>> {
    let mut found_license = false;
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let uppercase = name.to_ascii_uppercase();
        let is_license = ["LICENSE", "LICENCE", "COPYING"]
            .iter()
            .any(|prefix| uppercase.starts_with(prefix));
        if !(is_license || uppercase.starts_with("NOTICE")) || !entry.path().is_file() {
            continue;
        }
        let contents = fs::read_to_string(entry.path())?;
        if contents.trim().is_empty() {
            continue;
        }
        found_license |= is_license;
        licenses
            .entry(contents)
            .or_default()
            .insert(format!("{identity} — `{name}`"));
    }
    Ok(found_license)
}

/// 按 SPDX 表达式里出现的标识符返回已内置标准文本的许可（`OR` 取其中有文本的选项，`AND` 全部需要）；
/// 一个都没有时报错，由维护者补充 `xtask/licenses` 与此表。
fn standard_licenses(spdx: &str) -> Result<Vec<(&'static str, &'static str)>, Box<dyn Error>> {
    const KNOWN: [(&str, &str); 5] = [
        ("MIT", include_str!("../licenses/MIT.txt")),
        ("Apache-2.0", include_str!("../licenses/Apache-2.0.txt")),
        ("MPL-2.0", include_str!("../licenses/MPL-2.0.txt")),
        ("CC0-1.0", include_str!("../licenses/CC0-1.0.txt")),
        ("Zlib", include_str!("../licenses/Zlib.txt")),
    ];
    let tokens: Vec<&str> = spdx
        .split(|c: char| c.is_whitespace() || matches!(c, '/' | '(' | ')'))
        .collect();
    let found: Vec<_> = KNOWN
        .iter()
        .copied()
        .filter(|(id, _)| tokens.contains(id))
        .collect();
    if found.is_empty() {
        return Err(format!("缺少 SPDX {spdx} 的标准许可文本").into());
    }
    Ok(found)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn collects_and_deduplicates_exact_text_without_changing_notices() {
        let directory = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join(format!("../target/kanso-notices-{}", std::process::id()));
        fs::create_dir_all(&directory).unwrap();
        let notice = "Copyright upstream\r\n\r\nKeep this NOTICE.\r\n";
        fs::write(directory.join("LICENSE-MIT"), "Permission\n").unwrap();
        fs::write(directory.join("LICENCE"), "Permission\n").unwrap();
        fs::write(directory.join("COPYING"), "Permission\n\n").unwrap();
        fs::write(directory.join("NOTICE.txt"), notice).unwrap();
        fs::write(directory.join("README.md"), "Not a license").unwrap();
        fs::create_dir_all(directory.join("LICENSES")).unwrap();
        let mut licenses = LicenseTexts::new();
        assert!(collect_license_files(&directory, "first@1.0", &mut licenses).unwrap());
        assert!(collect_license_files(&directory, "second@2.0", &mut licenses).unwrap());
        assert_eq!(licenses.len(), 3);
        assert_eq!(licenses["Permission\n"].len(), 4);
        assert_eq!(licenses[notice].len(), 2);
        fs::remove_dir_all(&directory).unwrap();
    }

    #[test]
    fn notice_alone_still_requires_standard_license_text() {
        let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join(format!(
            "../target/kanso-notice-only-{}",
            std::process::id()
        ));
        fs::create_dir_all(&directory).unwrap();
        fs::write(directory.join("NOTICE"), "Upstream notice\n").unwrap();
        let mut licenses = LicenseTexts::new();
        assert!(!collect_license_files(&directory, "example@1.0", &mut licenses).unwrap());
        assert_eq!(licenses.len(), 1);
        let standards = standard_licenses("Apache-2.0/MIT").unwrap();
        assert_eq!(standards.len(), 2);
        assert!(standards[0].1.contains("Permission is hereby granted"));
        assert!(standards[1].1.contains("Version 2.0, January 2004"));
        assert!(
            standard_licenses("MPL-2.0").unwrap()[0]
                .1
                .contains("Mozilla Public License")
        );
        assert!(standard_licenses("unknown").is_err());
        fs::remove_dir_all(&directory).unwrap();
    }
}
