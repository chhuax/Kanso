type LicenseTexts = BTreeMap<String, BTreeSet<String>>;

pub fn generate() -> ExitCode {
    match write_notices() {
        Ok(()) => {
            eprintln!("已生成 THIRD_PARTY_NOTICES.md");
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("生成第三方声明失败：{error}");
            ExitCode::FAILURE
        }
    }
}

fn output(args: &[&str]) -> Result<String, Box<dyn Error>> {
    let result = cargo().args(args).output()?;
    if !result.status.success() {
        return Err(String::from_utf8_lossy(&result.stderr).into_owned().into());
    }
    Ok(String::from_utf8(result.stdout)?)
}

